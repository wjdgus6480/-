const DRAFT_NOTICE = '이 문서는 공개 전 검토 중인 초안입니다.';

function Contact() {
  const c = publicConfig.contactEmail;
  return c ? <a href={`mailto:${c}`}>{c}</a> : <span>(운영자 문의처 준비 중 — 설정 화면의 회원 탈퇴·데이터 내보내기는 지금도 이용할 수 있습니다)</span>;
}

